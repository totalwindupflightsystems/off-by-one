func TestExecutor_Commit_StoresAnswer(t *testing.T) {
	ex, store, _ := newTestSolver(t, "")
	sol, err := ex.Solve(context.Background(), sampleEntry("sub-commit"))
	if err != nil {
		t.Fatalf("Solve: %v", err)
	}
	answerID, err := ex.Commit(context.Background(), sampleEntry("sub-commit"), sol)
	if err != nil {
		t.Fatalf("Commit: %v", err)
	}
	if answerID == 0 {
		t.Error("answerID = 0")
	}
	// Verify the row exists in the graph.
	answer, err := store.GetAnswerNode(context.Background(), answerID)
	if err != nil {
		t.Fatalf("GetAnswerNode: %v", err)
	}
	if answer.Solution != sol.SolutionMarkdown {
		t.Errorf("answer.Solution = %q, want %q", answer.Solution, sol.SolutionMarkdown)
	}
	if answer.Evidence != sol.EvidenceMarkdown {
		t.Errorf("answer.Evidence = %q, want %q", answer.Evidence, sol.EvidenceMarkdown)
	}
	if answer.Env != "docker" || answer.Lang != "go" || answer.Version != "1.26" {
		t.Errorf("answer scope = (%q, %q, %q), want (docker, go, 1.26)",
			answer.Env, answer.Lang, answer.Version)
	}
	// Status should be verified right after commit (MVP — validator ring deferred).
	if answer.Status != graph.AnswerVerified {
		t.Errorf("answer.Status = %q, want %q", answer.Status, graph.AnswerVerified)
	}
}

