func TestExecutor_Solve_PropagatesAPIVars(t *testing.T) {
	// Custom runner that records the env passed to Exec.
	rec := &recordingRunner{root: t.TempDir()}
	store, err := graph.OpenShared(fmt.Sprintf("test-solver-env-%d", time.Now().UnixNano()))
	if err != nil {
		t.Fatalf("graph.OpenShared: %v", err)
	}
	defer store.Close()
	ex := NewExecutor(Config{
		PiAgentPath: "/bin/true",
		Model:       "deepseek-v4-flash",
		APIKey:      "sk-test-key-1234",
		Timeout:     5 * time.Second,
	}, rec, store)
	_, _ = ex.Solve(context.Background(), sampleEntry("sub-env"))
	rec.mu.Lock()
	defer rec.mu.Unlock()
	// The handle updates its OWN lastEnv (separate field from
	// the runner's lastEnv) — read it via the handle.
	if rec.lastHandle == nil {
		t.Fatal("Exec was not called")
	}
	// rec.mu and lastHandle.mu are the SAME pointer — we already
	// hold rec.mu, so we can read lastEnv without re-locking.
	env := rec.lastHandle.lastEnv
	if len(env) == 0 {
		t.Fatal("Exec was called with empty env")
	}
	hasKey := false
	for _, e := range env {
		if strings.HasPrefix(e, "DEEPSEEK_API_KEY=") {
			hasKey = true
		}
	}
	if !hasKey {
		t.Errorf("env did not include DEEPSEEK_API_KEY: %v", env)
	}
}

// recordingRunner records the env passed to its handle's Exec
// call. It uses a real filesystem so the test exercises the full
// Solve flow.
type recordingRunner struct {
	mu         sync.Mutex
	root       string
	lastHandle *recordingHandle
}

type recordingHandle struct {
	root    string
	lastEnv []string
	mu      *sync.Mutex
}

func (r *recordingRunner) Create(ctx context.Context, id string) (Handle, error) {
	root, err := os.MkdirTemp(r.root, "rec-*"+id+"-*")
	if err != nil {
		return nil, err
	}
	r.mu.Lock()
	r.lastHandle = &recordingHandle{root: root, mu: &r.mu}
	h := r.lastHandle
	r.mu.Unlock()
	return h, nil
}

func (h *recordingHandle) WriteFile(relPath string, data []byte) error {
	full := filepath.Join(h.root, relPath)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return err
	}
	return os.WriteFile(full, data, 0o644)
}

func (h *recordingHandle) ReadFile(relPath string) ([]byte, error) {
	return os.ReadFile(filepath.Join(h.root, relPath))
}

func (h *recordingHandle) Exec(ctx context.Context, name string, args, env []string) ([]byte, error) {
	h.mu.Lock()
	h.lastEnv = append([]string{}, env...)
	h.mu.Unlock()
	// Write a minimal solution to make Solve succeed.
	_ = h.WriteFile("solution.md", []byte("# Solved\nOK.\n"))
	_ = h.WriteFile("evidence.md", []byte("# Evidence\nOK.\n"))
	_ = h.WriteFile("signatures.json", []byte(`{"problem_class":"x"}`))
	return []byte("rec-ok\n"), nil
}

func (h *recordingHandle) Destroy() error {
	if h.root == "" {
		return nil
	}
	err := os.RemoveAll(h.root)
	h.root = ""
	return err
}

func TestExecutor_Solve_Concurrent(t *testing.T) {
	// Run N solves in parallel against independent handles.
	// This stresses the lock-free handoff between Solve() and
	// Commit() — we don't Commit, just Solve, so the graph is
	// untouched.
	ex, _, _ := newTestSolver(t, "")
	const n = 8
	var wg sync.WaitGroup
	errs := make([]error, n)
	for i := 0; i < n; i++ {
		i := i
		wg.Add(1)
		go func() {
			defer wg.Done()
			entry := sampleEntry(fmt.Sprintf("sub-conc-%d", i))
			_, err := ex.Solve(context.Background(), entry)
			errs[i] = err
		}()
	}
	wg.Wait()
	for i, e := range errs {
		if e != nil {
			t.Errorf("solve %d: %v", i, e)
		}
	}
}

