// fakeRunner is a filesystem-based Runner for tests. It does not
// spawn bwrap, does not require a real pi-agent binary, and is
// safe for concurrent use.
//
// Each Create returns a fresh handle backed by a unique
// t.TempDir-equivalent (we use os.MkdirTemp under t.TempDir so
// the directory is auto-cleaned). The handle's WriteFile /
// ReadFile are direct filesystem ops; Exec writes stdout to a
// file and returns it. A `piagentScript` may be set on the runner
// to override the default behavior.
type fakeRunner struct {
	mu         sync.Mutex
	script     string
	piAgentDir string
}

type fakeHandle struct {
	root    string
	stdout  []byte
	execErr error
}

func newFakeRunner(t *testing.T, script string) *fakeRunner {
	t.Helper()
	dir := t.TempDir()
	piAgent := filepath.Join(dir, "pi-agent")
	// Default script: write a minimal solution.md, evidence.md,
	// and signatures.json. Tests can override via the `script`
	// arg to newFakeRunner to simulate failures.
	if script == "" {
		script = defaultFakePiAgent
	}
	if err := os.WriteFile(piAgent, []byte(script), 0o755); err != nil {
		t.Fatalf("write fake pi-agent: %v", err)
	}
	return &fakeRunner{piAgentDir: dir, script: script}
}

const defaultFakePiAgent = `#!/bin/sh
# Default fake pi-agent: writes a minimal solution + evidence +
# signatures bundle based on flags.
PROBLEM=""
OUTPUT=""
EVIDENCE=""
SIGNATURES=""
MODEL="unknown"
while [ $# -gt 0 ]; do
  case "$1" in
    --problem-file) PROBLEM="$2"; shift 2 ;;
    --output) OUTPUT="$2"; shift 2 ;;
    --evidence) EVIDENCE="$2"; shift 2 ;;
    --signatures) SIGNATURES="$2"; shift 2 ;;
    --model) MODEL="$2"; shift 2 ;;
    *) shift ;;
  esac
done
# Read the problem to extract a class.
CLASS="unknown"
if [ -f "$PROBLEM" ]; then
  CLASS=$(grep -o '"problem_class"[[:space:]]*:[[:space:]]*"[^"]*"' "$PROBLEM" | head -1 | sed 's/.*"\(.*\)"/\1/')
fi
cat > "$OUTPUT" << EOF
# Solution for $CLASS
This is the auto-generated answer for the problem.
## Steps
1. Diagnose
2. Fix
3. Verify
EOF
cat > "$EVIDENCE" << EOF
# Evidence
Reproducer attached.
EOF
cat > "$SIGNATURES" << EOF
{
  "problem_class": "$CLASS",
  "description": "auto-generated by fake pi-agent",
  "environment": "docker",
  "language": "go",
  "version": "1.26",
  "model": "$MODEL"
}
EOF
exit 0
`

func (r *fakeRunner) Create(ctx context.Context, id string) (Handle, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	root, err := os.MkdirTemp(r.piAgentDir, "ws-*"+id+"-*")
	if err != nil {
		return nil, err
	}
	return &fakeHandle{root: root}, nil
}

func (h *fakeHandle) WriteFile(relPath string, data []byte) error {
	full := filepath.Join(h.root, relPath)
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return err
	}
	return os.WriteFile(full, data, 0o644)
}

func (h *fakeHandle) ReadFile(relPath string) ([]byte, error) {
	return os.ReadFile(filepath.Join(h.root, relPath))
}

func (h *fakeHandle) Exec(ctx context.Context, name string, args, env []string) ([]byte, error) {
	// We don't actually exec the script. Instead, we mirror the
	// defaultFakePiAgent's behaviour by writing the same files
	// (because the test's runner already wrote the script but
	// we want to control the outcome).
	// For tests that want full control, the test sets h.execErr
	// and we just return that.
	if h.execErr != nil {
		return h.stdout, h.execErr
	}
	// Find the --output / --evidence / --signatures paths.
	output := ""
	evidence := ""
	signatures := ""
	model := "unknown"
	problem := ""
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "--output":
			if i+1 < len(args) {
				output = args[i+1]
				i++
			}
		case "--evidence":
			if i+1 < len(args) {
				evidence = args[i+1]
				i++
			}
		case "--signatures":
			if i+1 < len(args) {
				signatures = args[i+1]
				i++
			}
		case "--model":
			if i+1 < len(args) {
				model = args[i+1]
				i++
			}
		case "--problem-file":
			if i+1 < len(args) {
				problem = args[i+1]
				i++
			}
		}
	}
	// Translate /workspace/... paths to the workspace root.
	// Inside bwrap the workspace is mounted at /workspace; in
	// the fake, paths point at our local temp dir directly.
	readProblem := stripWorkspace(problem)
	output = stripWorkspace(output)
	evidence = stripWorkspace(evidence)
	signatures = stripWorkspace(signatures)
	class := "unknown"
	if readProblem != "" {
		if data, err := h.ReadFile(readProblem); err == nil {
			class = extractClassFromProblem(data)
		}
	}
	if output != "" {
		_ = h.WriteFile(output, []byte(fmt.Sprintf("# Solution for %s\nAuto-generated.\n", class)))
	}
	if evidence != "" {
		_ = h.WriteFile(evidence, []byte("# Evidence\nauto-generated.\n"))
	}
	if signatures != "" {
		_ = h.WriteFile(signatures, []byte(fmt.Sprintf(
			`{"problem_class":"%s","environment":"docker","language":"go","version":"1.26","model":"%s"}`,
			class, model)))
	}
	return []byte("fake pi-agent ok\n"), nil
}

func (h *fakeHandle) Destroy() error {
	if h.root == "" {
		return nil
	}
	err := os.RemoveAll(h.root)
	h.root = ""
	return err
}

func stripWorkspace(p string) string {
	if strings.HasPrefix(p, "/workspace/") {
		return strings.TrimPrefix(p, "/workspace/")
	}
	return p
}

func extractClassFromProblem(data []byte) string {
	var p struct {
		ProblemClass string `json:"problem_class"`
	}
	if err := json.Unmarshal(data, &p); err == nil && p.ProblemClass != "" {
		return p.ProblemClass
	}
	return "unknown"
}

// newTestSolver returns a solver wired to a fake runner and a
// fresh in-memory graph. Returns the solver, the store, and a
// cleanup function.
func newTestSolver(t *testing.T, script string) (*Executor, *graph.Store, *fakeRunner) {
	t.Helper()
	runner := newFakeRunner(t, script)
	store, err := graph.OpenShared(fmt.Sprintf("test-solver-%s-%d", t.Name(), time.Now().UnixNano()))
	if err != nil {
		t.Fatalf("graph.OpenShared: %v", err)
	}
	t.Cleanup(func() { _ = store.Close() })
	cfg := Config{
		PiAgentPath: filepath.Join(runner.piAgentDir, "pi-agent"),
		Model:       "deepseek-v4-flash",
		APIKey:      "sk-test-key",
		Timeout:     5 * time.Second,
	}
	ex := NewExecutor(cfg, runner, store)
	return ex, store, runner
}

